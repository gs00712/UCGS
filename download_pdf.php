<?php

session_start();

require_once __DIR__ . "/../config/database.php";
require_once __DIR__ . "/../fpdf/fpdf.php";

if (!isset($_GET["id"]) || !is_numeric($_GET["id"])) {
    die("Invalid complaint ID.");
}

$complaint_id = (int) $_GET["id"];


/* Check login */

$is_admin = isset($_SESSION["admin_id"]);
$is_department = isset($_SESSION["department_id"]);

if (!$is_admin && !$is_department) {

    header("Location: ../index.php");
    exit;

}


/* Get complaint */

$sql = "SELECT
            complaints.id,
            complaints.complaint_title,
            complaints.complaint_text,
            complaints.department,
            complaints.status,
            complaints.created_at,
            students.name AS student_name,
            students.email AS student_email
        FROM complaints
        INNER JOIN students
        ON complaints.student_id = students.id
        WHERE complaints.id = ?
        AND complaints.status = 'Resolved'";

$stmt = $conn->prepare($sql);

$stmt->bind_param("i", $complaint_id);

$stmt->execute();

$result = $stmt->get_result();

if ($result->num_rows === 0) {

    die("Complaint not found or complaint is not resolved.");

}

$complaint = $result->fetch_assoc();


/*
    Department users can download
    only their own department complaints.

    Admin can download
    any resolved complaint.
*/

if ($is_department && !$is_admin) {

    $department_name = $_SESSION["department_name"];

    if ($complaint["department"] !== $department_name) {

        die("You are not authorized to download this report.");

    }

}


/* Get resolved date */

$resolved_sql = "SELECT changed_at
                 FROM complaint_status_history
                 WHERE complaint_id = ?
                 AND new_status = 'Resolved'
                 ORDER BY changed_at DESC
                 LIMIT 1";

$resolved_stmt = $conn->prepare($resolved_sql);

$resolved_stmt->bind_param("i", $complaint_id);

$resolved_stmt->execute();

$resolved_result = $resolved_stmt->get_result();

$resolved_date = "Not available";

if ($resolved_result->num_rows > 0) {

    $resolved_data = $resolved_result->fetch_assoc();

    $resolved_date = $resolved_data["changed_at"];

}


/* Create PDF */

$pdf = new FPDF();

$pdf->AddPage();

$pdf->SetFont("Arial", "B", 18);

$pdf->Cell(
    0,
    10,
    "UCGS - Resolved Complaint Report",
    0,
    1,
    "C"
);

$pdf->Ln(5);


/* Complaint Information */

$pdf->SetFont("Arial", "B", 12);

$pdf->Cell(
    0,
    8,
    "Complaint Information",
    0,
    1
);

$pdf->SetFont("Arial", "", 11);

$pdf->Cell(45, 8, "Complaint ID:", 0, 0);

$pdf->Cell(
    0,
    8,
    "#" . $complaint["id"],
    0,
    1
);

$pdf->Cell(45, 8, "Title:", 0, 0);

$pdf->Cell(
    0,
    8,
    $complaint["complaint_title"],
    0,
    1
);

$pdf->Cell(45, 8, "Department:", 0, 0);

$pdf->Cell(
    0,
    8,
    $complaint["department"],
    0,
    1
);

$pdf->Cell(45, 8, "Status:", 0, 0);

$pdf->Cell(
    0,
    8,
    "RESOLVED",
    0,
    1
);

$pdf->Cell(45, 8, "Submitted On:", 0, 0);

$pdf->Cell(
    0,
    8,
    $complaint["created_at"],
    0,
    1
);

$pdf->Cell(45, 8, "Resolved On:", 0, 0);

$pdf->Cell(
    0,
    8,
    $resolved_date,
    0,
    1
);

$pdf->Ln(5);


/* Student Information */

$pdf->SetFont("Arial", "B", 12);

$pdf->Cell(
    0,
    8,
    "Student Information",
    0,
    1
);

$pdf->SetFont("Arial", "", 11);

$pdf->Cell(45, 8, "Student Name:", 0, 0);

$pdf->Cell(
    0,
    8,
    $complaint["student_name"],
    0,
    1
);

$pdf->Cell(45, 8, "College Email:", 0, 0);

$pdf->Cell(
    0,
    8,
    $complaint["student_email"],
    0,
    1
);

$pdf->Ln(5);


/* Complaint Details */

$pdf->SetFont("Arial", "B", 12);

$pdf->Cell(
    0,
    8,
    "Complaint Details",
    0,
    1
);

$pdf->SetFont("Arial", "", 11);

$pdf->MultiCell(
    0,
    7,
    $complaint["complaint_text"]
);

$pdf->Ln(10);


/* Footer */

$pdf->SetFont("Arial", "I", 9);

if ($is_admin) {

    $generated_by = "Generated by UCGS Admin Portal";

} else {

    $generated_by = "Generated by UCGS Department Portal";

}

$pdf->Cell(
    0,
    8,
    $generated_by,
    0,
    1,
    "C"
);


/* Download PDF */

$filename = "Complaint_Report_" . $complaint["id"] . ".pdf";

$pdf->Output(
    "D",
    $filename
);

?>